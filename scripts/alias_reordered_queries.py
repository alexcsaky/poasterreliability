"""One-off (D-023): point re-ordered search queries at responses already stored.

Before D-023, cohort sweeps and signals-x sorted search terms by length only, so equal-length terms came out in
hash order and each run built a differently ordered query (a cache miss). This replays `signals-x` and the cohort
sweeps with the network disabled. For every request that misses the store, it looks for a stored 2xx response to
the same endpoint whose parameters are identical except for the order of the quoted terms in the query; if one
exists, the same body is stored again (unmodified) under the new request key with usd=0, so nothing is billed
twice and `rebuild` can replay it. Requests with no such match are left for the next real run (and reported).
No network calls, no spend."""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from xrf import cohort, config, rawstore, signals_x, state, xapi  # noqa: E402
from xrf.cli import _conn  # noqa: E402

QUOTED = re.compile(r'"[^"]+"')
EMPTY = b'{"meta":{"result_count":0}}'
stats = {"hit": 0, "aliased": 0, "unmatched": []}


def _shape(params: dict) -> tuple:
    q = params.get("query", "")
    rest = {k: v for k, v in params.items() if k != "query"}
    return QUOTED.sub('""', q), tuple(sorted(QUOTED.findall(q))), json.dumps(rest, sort_keys=True)


def main() -> None:
    conn = _conn()
    stored = {}
    for rid, ep, pj in conn.execute("SELECT id, endpoint, params_json FROM raw_responses "
                                    "WHERE status BETWEEN 200 AND 299 AND provider='x'"):
        stored.setdefault((ep, _shape(json.loads(pj))), rid)

    def call(conn_, *, provider, endpoint, params, budget, worst_case_usd, do_request, cost_of):
        key = rawstore.request_key(provider, endpoint, params)
        hit = rawstore.lookup(conn_, key)
        if hit:
            stats["hit"] += 1
            return hit
        rid = stored.get((endpoint, _shape(params)))
        if rid is None:
            stats["unmatched"].append(params.get("_tag"))
            return rawstore.Raw(-1, 200, EMPTY, "", True)   # not stored: the next real run fetches it
        status, path = conn_.execute("SELECT status, body_path FROM raw_responses WHERE id=?", (rid,)).fetchone()
        stats["aliased"] += 1
        return rawstore.store(conn_, key, provider, endpoint, params, status, rawstore.load_body(path), 0.0)

    def no_network(*a, **k):
        raise RuntimeError("network disabled in alias script")

    rawstore.call = call
    xapi._send = no_network
    keep = (config.LEDGER / "signals_x.csv").read_bytes()
    signals_x.collect(conn, log=lambda *a: None)
    (config.LEDGER / "signals_x.csv").write_bytes(keep)   # regenerated by the next real `signals-x` run
    as_of = datetime.fromisoformat(state.get("cohort_as_of").replace("Z", "+00:00"))
    cohort.sweep(conn, as_of, log=lambda *a: None)
    print(json.dumps({"already_matching": stats["hit"], "aliased": stats["aliased"],
                      "unmatched": len(stats["unmatched"]), "unmatched_tags": stats["unmatched"]}, indent=2))


if __name__ == "__main__":
    main()
